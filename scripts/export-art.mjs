#!/usr/bin/env node
/**
 * Exports the app's flat art (teachers, avatars, objects, phone icons, map glyphs) into
 * `src/art/generated.ts` as plain SVG strings, so the landing page shows the SAME drawings the
 * app does without depending on the app at runtime. Shrodi is copied as live code (`src/art/shrodi`).
 *
 * Usage: node scripts/export-art.mjs [path-to-AtomIQ-repo]   (default: ../AtomIQ)
 * Needs Node >= 22.13 (it imports the app's erasable-syntax .ts files directly).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(process.argv[2] ?? path.join(HERE, "..", "..", "AtomIQ"));
const load = (p) => import(pathToFileURL(path.join(APP, p)).href);

const npc = await load("components/npc/npc-art.ts");
const { NPC_ROSTER } = await load("components/npc/npc-roster.ts");
const { OBJECT_ART, ART_NAMES } = await load("components/lesson/visual/object-art.ts");
const { APP_ICON_ART, APP_ICON_TILE, ICON_TILES } = await load("components/phone/app-icon-art.ts");
const { PHONE_APPS } = await load("services/phone-core.ts");
const { GLYPHS, GLYPH_VIEWBOX } = await load("components/path/node-glyphs.ts");
const avatar = await load("components/avatar/avatar-core.ts");

const f = (n) => Math.round(n * 100) / 100;

// ── teachers & avatars ──────────────────────────────────────────────────────
const figure = (spec, pose, form) => {
  const vb = npc.NPC_VIEWBOX[form];
  const tree = npc.buildNpc(spec, pose, form);
  return { viewBox: `${vb.x} ${vb.y} ${vb.w} ${vb.h}`, svg: npc.treeParts(tree).map(npc.partToSvg).join("") };
};
const teachers = NPC_ROSTER.map((n) => ({
  id: n.id,
  name: n.name,
  title: n.title,
  unitId: n.unitId,
  color: n.spec.outfit.color,
  bust: figure(n.spec, "idle", "bust"),
  head: figure(n.spec, "idle", "head"),
  hero: figure(n.spec, "greet", "hero"),
}));
const avatars = avatar.STARTER_AVATARS.map((a) => ({
  id: a.id,
  label: a.label,
  background: avatar.avatarBackground(a.config),
  ...figure(avatar.avatarSpec(a.config), "idle", "avatar"),
}));

// ── objects, icons, glyphs ─────────────────────────────────────────────────
const shape = (s, face, lip) => {
  const c = (v) => (v === "$face" ? face : v === "$lip" ? lip : v);
  const op = s.opacity === undefined ? "" : ` fill-opacity="${s.opacity}"`;
  if (s.t === "rect") return `<rect x="${f(s.x)}" y="${f(s.y)}" width="${f(s.w)}" height="${f(s.h)}" rx="${f(s.r)}" fill="${c(s.fill)}"${op}/>`;
  if (s.t === "circle") return `<circle cx="${f(s.cx)}" cy="${f(s.cy)}" r="${f(s.r)}" fill="${c(s.fill)}"${op}/>`;
  if (s.t === "path") return `<path d="${s.d}" fill="${c(s.fill)}"${op}/>`;
  return `<path d="${s.d}" fill="none" stroke="${c(s.stroke)}" stroke-width="${s.width}" stroke-linecap="round" stroke-linejoin="round"/>`;
};
const objects = Object.fromEntries(Object.keys(OBJECT_ART).map((id) => [id, { name: ART_NAMES[id], svg: OBJECT_ART[id].map((s) => shape(s)).join("") }]));

const TILES = {
  yellow: ["#FFC800", "#E6A800"], blue: ["#1CB0F6", "#1899D6"], green: ["#46A302", "#378300"], purple: ["#9069CD", "#6F4EA1"],
  red: ["#FF4B4B", "#D93B3B"], orange: ["#FF9600", "#DA7C00"], cyan: ["#00CDE7", "#00A4BA"], coral: ["#FF8A80", "#CC6E66"], grey: ["#767676", "#5E5E5E"],
};
const appIcons = {};
for (const a of PHONE_APPS.filter((x) => APP_ICON_ART[x.id])) {
  const own = APP_ICON_TILE[a.id];
  const [face, lip] = own ? [ICON_TILES[own].face, ICON_TILES[own].lip] : TILES[a.color];
  appIcons[a.id] = { name: a.name, face, lip, svg: APP_ICON_ART[a.id].map((s) => shape(s, face, lip)).join("") };
}

const glyphSvg = (g) => {
  const inner = g.shapes
    .map((s) => {
      const fill = s.fill ?? s.sw === undefined;
      return `<path d="${s.d}" fill="${fill ? "#fff" : "none"}"${fill && s.evenOdd ? ' fill-rule="evenodd"' : ""}${s.sw ? ` stroke="#fff" stroke-width="${s.sw}" stroke-linecap="round" stroke-linejoin="round"` : ""}/>`;
    })
    .join("");
  return g.rotate ? `<g transform="rotate(${g.rotate} 24 24)">${inner}</g>` : inner;
};
const glyphs = Object.fromEntries(Object.keys(GLYPHS).map((id) => [id, glyphSvg(GLYPHS[id])]));

const out = `/* GENERATED by scripts/export-art.mjs from the AtomIQ app. Do not edit by hand; re-run the script. */

export interface Figure { viewBox: string; svg: string }
export interface Teacher { id: string; name: string; title: string; unitId: string; color: string; bust: Figure; head: Figure; hero: Figure }
export interface Avatar extends Figure { id: string; label: string; background: string }
export interface AppIconArt { name: string; face: string; lip: string; svg: string }

export const TEACHERS: Teacher[] = ${JSON.stringify(teachers)}

export const AVATARS: Avatar[] = ${JSON.stringify(avatars)}

/** Lesson object pictures on a 100-unit frame, keyed by the app's art id. */
export const OBJECTS: Record<string, { name: string; svg: string }> = ${JSON.stringify(objects)}

/** Phone app tiles (face, lip, picture) on a 100-unit frame, keyed by the app id. */
export const APP_ICONS: Record<string, AppIconArt> = ${JSON.stringify(appIcons)}

/** Lesson-map node pictures, white on a ${GLYPH_VIEWBOX}-unit frame. */
export const GLYPH_VIEWBOX = ${GLYPH_VIEWBOX}
export const GLYPHS: Record<string, string> = ${JSON.stringify(glyphs)}
`;
fs.writeFileSync(path.join(HERE, "..", "src", "art", "generated.ts"), out);
console.log(`wrote src/art/generated.ts: ${teachers.length} teachers, ${avatars.length} avatars, ${Object.keys(objects).length} objects, ${Object.keys(appIcons).length} app icons, ${Object.keys(glyphs).length} glyphs (${Math.round(out.length / 1024)} KB)`);
